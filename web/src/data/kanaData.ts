// ── Number Generator ──────────────────────────────────────────────────────
const DIGITS = ['', 'ichi', 'ni', 'san', 'yon', 'go', 'roku', 'nana', 'hachi', 'kyuu'];
const DIGITS_JP = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];

export function intToJapanese(n: number): [string, string] {
  if (n === 0) return ['零', 'rei'];
  if (n < 0 || n > 99999) return [String(n), String(n)];

  let jp = '';
  let romaji = '';

  const wan = Math.floor(n / 10000);
  let rem = n % 10000;
  if (wan > 0) {
    const [subJp, subRo] = intToJapanese(wan);
    jp += subJp + '万';
    romaji += subRo + 'man ';
  }

  const sen = Math.floor(rem / 1000);
  rem %= 1000;
  if (sen > 0) {
    if (sen === 3) {
      jp += '三千';
      romaji += 'sanzen ';
    } else if (sen === 8) {
      jp += '八千';
      romaji += 'hassen ';
    } else if (sen === 1) {
      jp += '千';
      romaji += 'sen ';
    } else {
      jp += DIGITS_JP[sen] + '千';
      romaji += DIGITS[sen] + 'sen ';
    }
  }

  const hyaku = Math.floor(rem / 100);
  rem %= 100;
  if (hyaku > 0) {
    if (hyaku === 3) {
      jp += '三百';
      romaji += 'sanbyaku ';
    } else if (hyaku === 6) {
      jp += '六百';
      romaji += 'roppyaku ';
    } else if (hyaku === 8) {
      jp += '八百';
      romaji += 'happyaku ';
    } else if (hyaku === 1) {
      jp += '百';
      romaji += 'hyaku ';
    } else {
      jp += DIGITS_JP[hyaku] + '百';
      romaji += DIGITS[hyaku] + 'hyaku ';
    }
  }

  const juu = Math.floor(rem / 10);
  const single = rem % 10;

  if (juu > 0) {
    if (juu === 1) {
      jp += '十';
      romaji += 'juu ';
    } else {
      jp += DIGITS_JP[juu] + '十';
      romaji += DIGITS[juu] + 'juu ';
    }
  }

  if (single > 0) {
    jp += DIGITS_JP[single];
    romaji += DIGITS[single];
  }

  return [jp.trim(), romaji.trim().toLowerCase()];
}

export function generateRandomNumberEntries(count: number = 20): KanaEntry[] {
  const result: KanaEntry[] = [];
  for (let i = 0; i < count; i++) {
    const d = Math.floor(Math.random() * 5) + 1;
    let val = 1;
    if (d === 1) val = Math.floor(Math.random() * 9) + 1;
    else if (d === 2) val = Math.floor(Math.random() * 90) + 10;
    else if (d === 3) val = Math.floor(Math.random() * 900) + 100;
    else if (d === 4) val = Math.floor(Math.random() * 9000) + 1000;
    else val = Math.floor(Math.random() * 90000) + 10000;

    const [jp, romaji] = intToJapanese(val);
    result.push({
      kana: String(val),
      romaji,
      hint: jp,
    });
  }
  return result;
}
