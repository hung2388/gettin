const COLOR_MAP: Record<string, string> = {
  R: '#ff4757',
  G: '#2ed573',
  Y: '#ffa502',
  B: '#1e90ff',
  W: '#ffffff',
  D: '#2f3542',
  O: '#ff7f50',
};

export const PixelIcon: React.FC<PixelIconProps> = ({
  name,
  size = 16,
  className = '',
  color = 'currentColor',
}) => {
  const iconData = ICON_BITMAPS[name] || ICON_BITMAPS.sparkle;
  const { width, height, rows } = iconData;

  const rects: { x: number; y: number; fill: string }[] = [];

  rows.forEach((row, y) => {
    for (let x = 0; x < width; x++) {
      const char = row[x];
      if (char && char !== '.') {
        const fill = COLOR_MAP[char] || color;
        rects.push({ x, y, fill });
      }
    }
  });

  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      width={size}
      height={size}
      className={`inline-block shrink-0 select-none ${className}`}
      style={{
        shapeRendering: 'crispEdges',
        imageRendering: 'pixelated',
      }}
      aria-hidden="true"
    >
      {rects.map((rect, i) => (
        <rect
          key={i}
          x={rect.x}
          y={rect.y}
          width={1}
          height={1}
          fill={rect.fill}
        />
      ))}
    </svg>
  );
};
