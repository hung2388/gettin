def get_words_for_type(kana_type) -> List[WordEntry]:
    """Get words matching the given KanaType enum."""
    from model.app_model import KanaType
    mapping = {
        KanaType.HIRAGANA: HIRAGANA_WORDS,
        KanaType.KATAKANA: KATAKANA_WORDS,
        KanaType.NUMBERS: NUMBER_WORDS,
        KanaType.DAYS_WEEK: DAYS_WEEK_WORDS,
        KanaType.DAYS_MONTH: DAYS_MONTH_WORDS,
        KanaType.MONTHS: MONTHS_WORDS,
        KanaType.YEARS: YEARS_WORDS,
        KanaType.BIRTH_YEAR: BIRTH_YEAR_WORDS,
        KanaType.PACK_00: PACK_00_WORDS,
        KanaType.PACK_01: PACK_01_WORDS,
        KanaType.PACK_02: PACK_02_WORDS,
        KanaType.PACK_03: PACK_03_WORDS,
    }
    if kana_type == KanaType.BOTH:
        return HIRAGANA_WORDS + KATAKANA_WORDS
    return list(mapping.get(kana_type, []))


